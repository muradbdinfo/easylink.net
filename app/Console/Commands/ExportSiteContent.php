<?php

namespace App\Console\Commands;

use App\Support\SiteContentSync;
use Illuminate\Console\Command;

class ExportSiteContent extends Command
{
    protected $signature = 'site:export';

    protected $description = 'Snapshot the admin content (packages, services, settings ...) and create a migration that imports it on the live site';

    public function handle(): int
    {
        $stamp = now()->format('Y_m_d_His');
        $file = "site-content-{$stamp}.json";

        if (! is_dir(database_path('data'))) {
            mkdir(database_path('data'), 0755, true);
        }

        $data = SiteContentSync::export();
        file_put_contents(database_path("data/{$file}"), json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)."\n");

        $migration = <<<PHP
        <?php

        use App\Support\SiteContentSync;
        use Illuminate\Database\Migrations\Migration;

        // Generated by "php artisan site:export": imports the content snapshot database/data/{$file}.
        return new class extends Migration
        {
            public function up(): void
            {
                \$path = database_path('data/{$file}');

                if (is_file(\$path)) {
                    SiteContentSync::import(json_decode(file_get_contents(\$path), true));
                }
            }

            public function down(): void
            {
                //
            }
        };

        PHP;

        $migrationFile = database_path("migrations/{$stamp}_sync_site_content.php");
        file_put_contents($migrationFile, $migration);

        foreach ($data as $table => $rows) {
            $this->line(str_pad($table, 16).count($rows));
        }

        $this->info("Saved database/data/{$file} and a migration. Commit both and push - the live site imports them on deploy.");

        return self::SUCCESS;
    }
}
